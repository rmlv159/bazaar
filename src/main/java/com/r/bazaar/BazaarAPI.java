package com.r.bazaar;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.r.bazaar.input.InputValidator;
import com.r.bazaar.lib.model.Backup;
import com.r.bazaar.lib.model.IntelliSyncConfig;
import com.r.bazaar.entity.model.Table;
import io.swagger.v3.oas.annotations.Parameter;
import jakarta.servlet.http.HttpServletRequest;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.zip.GZIPInputStream;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.ResponseEntity;
import org.springframework.util.StreamUtils;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.ResponseBody;
import org.springframework.web.bind.annotation.RestController;

@RestController("BazaarAPIControllerV1")
public class BazaarAPI {

    @Autowired
    private BackupRepo repo;
    @Autowired
    private InputValidator inputValidator;
    @Autowired
    private ObjectMapper objectMapper;

    @GetMapping("/v1/weekly-backups")
    public List<Backup> getWeekly() {
        return repo.getWeekly();
    }

    @GetMapping("/v1/fetch")
    @ResponseBody
    public IntelliSyncConfig fetch(
        @RequestParam("client-id")
        @Parameter(description = "Pre-registered and pre-configured customer id", required = true, example = "81348123")
        int clientId) {
        return repo.getIntelliSyncConfig(clientId);
    }

    //TODO delete?
    @PostMapping(path = "/v1/initialize/{customer}", produces = "application/json")
    @ResponseBody
    public IntelliSyncConfig postInitialization(
        //plus client id and secret for verification
        @PathVariable("client-id")
        @Parameter(description = "Pre-registered and pre-configured customer id", required = true, example = "81348123")
        int clientId) {

        IntelliSyncConfig intelliSyncConfig = new IntelliSyncConfig();

        intelliSyncConfig.getRelevantTables().add("CRONUS Danmark A_S$Customer");
        intelliSyncConfig.getSubstituteFields2CustomizedFields().put("[Has Error]", "[Has Error2]");

        return intelliSyncConfig;
    }

    //TODO make requests async

    @PostMapping(path = "/v1/schema")
    public ResponseEntity<String> receiveTableSchema(
        //plus client id and secret for verification
        @RequestParam("client-id")
        @Parameter(description = "Pre-registered and pre-configured customer id", required = true, example = "81348123")
        int clientId,
        @RequestParam("backup-id")
        @Parameter(description = "Backup id generated by client, will "
            + "change for new backup or failure",
            required = true, example = "e58ed763-928c-4155-bee9-fdbaaadc15f3")
        String backupId,
        @RequestBody
        Table table
    ) {
        try {
            inputValidator.runForSequencedTypes(table.getSequencedTypes());
            repo.cacheSeqTypes(table.getName(), table.getSequencedTypes());
            repo.cacheSchema(table.getName(), table.getSchema());
            return ResponseEntity.ok("Data received successfully");
            //TODO handle more specifically
        } catch (Exception e) {
            return ResponseEntity.badRequest().body("Expected gzipped content");
        }
    }

    @PostMapping(path = "/v1/back-up-status")
    public ResponseEntity<String> receiveBackUpStatus(
        //plus client id and secret for verification
        @RequestParam("client-id")
        @Parameter(description = "Pre-registered and pre-configured customer id", required = true, example = "81348123")
        int clientId,
        @RequestParam("backup-id")
        @Parameter(description = "Backup id generated by client, will "
            + "change for new backup or failure",
            required = true, example = "e58ed763-928c-4155-bee9-fdbaaadc15f3")
        String backupId,
        @RequestParam("status")
        @Parameter(description = "Status", required = true, example = "DONE")
        String status
    ) {
        try {
            if (status.equals("DONE")) {
                repo.backupDone(clientId, backupId);
            }
            return ResponseEntity.ok("Data received successfully");
            //TODO handle more specifically
        } catch (Exception e) {
            return ResponseEntity.badRequest().body("Something went wrong");
        }
    }

    @PostMapping(path = "/v1/encoded-compressed-row")
    public ResponseEntity<String> receiveEncodedCompressedRowData(
        HttpServletRequest request,
        @RequestHeader("Content-Encoding") String contentEncoding
        ,
        //plus client id and secret for verification
        @RequestParam("client-id")
        @Parameter(description = "Pre-registered and pre-configured customer id", required = true, example = "81348123")
            int clientId,
        @RequestParam("table-name")
        @Parameter(description = "", required = true, example = "CRONUS Danmark A_S$Customer")
        String tableName
    ) throws IOException {
        if (contentEncoding != null && contentEncoding.equals("gzip")) {
            GZIPInputStream gzipInputStream = new GZIPInputStream(request.getInputStream());
            String decompressed = StreamUtils.copyToString(gzipInputStream, StandardCharsets.UTF_8);

            ArrayList<String> data = objectMapper.readValue(decompressed,
                new TypeReference<>() {
                });
            try {
                //TODO impl separate methods for decoding
                repo.saveRow(clientId, "backupId", tableName, data);
            } catch (Exception e) {
                return ResponseEntity.badRequest().body("An error occurred");
            }
            return ResponseEntity.ok("Data received and decompressed successfully");
        }
        return ResponseEntity.badRequest().body("An error occurred");
    }

    @PostMapping(path = "/v1/compressed-row")
    public ResponseEntity<String> receiveCompressedRowData(
        HttpServletRequest request,
        @RequestHeader("Content-Encoding") String contentEncoding
        ,
        //plus client id and secret for verification
        @RequestParam("client-id")
        @Parameter(description = "Pre-registered and pre-configured customer id", required = true, example = "81348123")
        int clientId,
        @RequestParam("table-name")
        @Parameter(description = "", required = true, example = "CRONUS Danmark A_S$Customer")
        String tableName
    ) throws IOException {
        if (contentEncoding != null && contentEncoding.equals("gzip")) {
            GZIPInputStream gzipInputStream = new GZIPInputStream(request.getInputStream());
            String decompressed = StreamUtils.copyToString(gzipInputStream, StandardCharsets.UTF_8);

            ArrayList<String> data = objectMapper.readValue(decompressed,
                new TypeReference<>() {
                });
            try {
                repo.saveRow(clientId, "backupId", tableName, data);
            } catch (Exception e) {
                return ResponseEntity.badRequest().body("An error occurred");
            }
            return ResponseEntity.ok("Data received and decompressed successfully");
        }
        return ResponseEntity.badRequest().body("An error occurred");
    }

    @PostMapping(path = "/v1/row")
    public ResponseEntity<String> receiveRowData(
        HttpServletRequest request,
        //plus client id and secret for verification
        @RequestParam("client-id")
        @Parameter(description = "Pre-registered and pre-configured customer id", required = true, example = "81348123")
        int clientId,
        @RequestParam("backup-id")
        @Parameter(description = "Backup id generated by client, will "
            + "change for new backup or failure",
            required = true, example = "e58ed763-928c-4155-bee9-fdbaaadc15f3")
        String backupId,
        @RequestParam("table-name")
        @Parameter(description = "", required = true, example = "CRONUS Danmark A_S$Customer")
        String tableName,
        @RequestBody ArrayList<String> data
    ) throws IOException {
        try {
            repo.saveRow(clientId, backupId, tableName, data);
        } catch (Throwable t) {
            return ResponseEntity.badRequest().body("An error occurred");
        }
        return ResponseEntity.ok("Data received successfully");
    }
}


